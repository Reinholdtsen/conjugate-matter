#!/usr/bin/env python3
"""Does the spontaneous polarization (the vacuum J, K) break Lorentz invariance?  Can it supply a
vertex that sees single-particle momenta rather than the transfer?

Phase space T*M, coordinates (x^a, p_a), d = 4.  Lorentz acts as L = diag(Lam, Lam^{-T}).
omega = [[0,1],[-1,0]], eta = [[0,1],[1,0]] (#1 §2), H0 = diag(g, g^{-1}), I = omega^{-1} H,
J = eta^{-1} H, K = eta^{-1} omega (#11 §5).  Born rotation rho generated by I (#1 P3).
"""
import numpy as np

rng = np.random.default_rng(1)
Z4, I4 = np.zeros((4, 4)), np.eye(4)
gM = np.diag([1.0, -1.0, -1.0, -1.0])


def boost(n, rap):
    n = n / np.linalg.norm(n)
    B = np.eye(4)
    ch, sh = np.cosh(rap), np.sinh(rap)
    B[0, 0] = ch
    B[0, 1:] = B[1:, 0] = sh * n
    B[1:, 1:] = np.eye(3) + (ch - 1) * np.outer(n, n)
    return B


def rotation(axis, ang):
    a = axis / np.linalg.norm(axis)
    Kx = np.array([[0, -a[2], a[1]], [a[2], 0, -a[0]], [-a[1], a[0], 0]])
    R3 = np.eye(3) + np.sin(ang) * Kx + (1 - np.cos(ang)) * Kx @ Kx
    R = np.eye(4); R[1:, 1:] = R3
    return R


Lam = boost(rng.normal(size=3), 0.9) @ rotation(rng.normal(size=3), 1.1)
print("Lambda^T g Lambda - g (Lorentz check):", np.abs(Lam.T @ gM @ Lam - gM).max())
L = np.block([[Lam, Z4], [Z4, np.linalg.inv(Lam).T]])
Li = np.linalg.inv(L)
omega = np.block([[Z4, I4], [-I4, Z4]])
eta = np.block([[Z4, I4], [I4, Z4]])
K0 = np.linalg.inv(eta) @ omega


def report(tag, g):
    H0 = np.block([[g, Z4], [Z4, np.linalg.inv(g)]])
    J0 = np.linalg.inv(eta) @ H0
    I0 = np.linalg.inv(omega) @ H0
    print("--", tag, "--")
    print("  H0 positive definite:", bool(np.all(np.linalg.eigvalsh(H0) > 0)))
    print("  algebra: |I^2+1| %.1e  |J^2-1| %.1e  |K^2-1| %.1e  |IJ-K| %.1e" % (
        np.abs(I0 @ I0 + np.eye(8)).max(), np.abs(J0 @ J0 - np.eye(8)).max(),
        np.abs(K0 @ K0 - np.eye(8)).max(), np.abs(I0 @ J0 - K0).max()))
    print("  under the Lorentz map L: |L^T w L - w| %.1e  |L^T eta L - eta| %.1e  |L K L^-1 - K| %.1e  "
          "|L J L^-1 - J| %.1e  |L^T H L - H| %.1e" % (
              np.abs(L.T @ omega @ L - omega).max(), np.abs(L.T @ eta @ L - eta).max(),
              np.abs(L @ K0 @ Li - K0).max(), np.abs(L @ J0 @ Li - J0).max(), np.abs(L.T @ H0 @ L - H0).max()))
    rho = I0
    print("  Born rotation rho = I: |rho K rho^-1 + K| %.1e  |rho J rho^-1 + J| %.1e  (flipped)  "
          "|rho^T w rho - w| %.1e  |L rho L^-1 - rho| %.1e" % (
              np.abs(rho @ K0 @ np.linalg.inv(rho) + K0).max(), np.abs(rho @ J0 @ np.linalg.inv(rho) + J0).max(),
              np.abs(rho.T @ omega @ rho - omega).max(), np.abs(L @ rho @ Li - rho).max()))


report("Lorentzian g = diag(1,-1,-1,-1)", gM)
report("Euclidean g = 1 (positive H, as the compatibility theorem assumes)", np.eye(4))

print("\n-- a preferred frame u (Lorentz violation) lets one vertex see single-particle momenta --")
print("NR Galilean identity: sum_i |m V + k_i|^2 = 4 m^2 V^2 + 4 k^2 for legs k_i = (k, -k, k', -k'), |k| = |k'|")
mvec = rng.normal(size=3); kv = rng.normal(size=3); kpv = np.linalg.norm(kv) * rng.normal(size=3)
kpv = np.linalg.norm(kv) * kpv / np.linalg.norm(kpv)
mV = mvec
lhs = sum(np.dot(mV + ki, mV + ki) for ki in (kv, -kv, kpv, -kpv))
print("  numeric check: lhs = %.10f, 4|mV|^2 + 4k^2 = %.10f" % (lhs, 4 * mV @ mV + 4 * kv @ kv))
print("  per-leg profile exp(-|p_u|^2/(4 mu^2)) -> product exp(-k^2/mu^2) * exp(-m^2 V^2/mu^2):")
print("  the record's gate times a suppression in the pair's velocity V through the frame u.")
